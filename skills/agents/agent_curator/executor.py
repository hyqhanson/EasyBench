    @staticmethod
    def _convert_cel_affymetrix(cel_files: List[Path], out_h5ad: Path, ds_id: str) -> Optional[Dict[str, Any]]:
        """Convert Affymetrix .CEL files → .h5ad.

        Strategy:
          1. Try pyAffy (Python) first — lightweight, no R dependency
          2. If pyAffy unavailable, generate an R script using oligo::read.celfiles
          3. If neither works, treat as raw binary → skip with note
        """
        try:
            import pandas as pd
            import anndata as ad
            import numpy as np

            # ── Attempt 1: pyAffy ──
            try:
                from pyAffy import read_celfiles as pyaffy_read
                cel_paths = [str(p) for p in cel_files if p.stat().st_size > 1024]
                if cel_paths:
                    adata = pyaffy_read(cel_paths)
                    adata.write_h5ad(out_h5ad)
                    return {"id": ds_id, "status": "curated", "output_h5ad": str(out_h5ad),
                            "method": "pyAffy", "n_cells": adata.n_obs, "n_genes": adata.n_vars}
            except ImportError:
                pass

            # ── Attempt 2: Generate R script (oligo) ──
            r_script = ds_dir = cel_files[0].parent
            cel_dir = str(cel_files[0].parent)
            r_code = (
                'library(oligo)\n'
                'library(anndata)\n'
                f'cel_files <- list.files(path="{cel_dir}", pattern="\\\\\\\\.CEL$", '
                f'full.names=TRUE, ignore.case=TRUE)\n'
                'if (length(cel_files) == 0) {\n'
                f'  cel_files <- list.files(path="{cel_dir}", pattern="\\\\\\\\.CEL\\\\\\\\.gz$", '
                f'full.names=TRUE, ignore.case=TRUE)\n'
                '}\n'
                'raw_data <- read.celfiles(filenames=cel_files)\n'
                'eset <- rma(raw_data)\n'
                'exprs_matrix <- exprs(eset)\n'
                'colnames(exprs_matrix) <- sampleNames(eset)\n'
                'rownames(exprs_matrix) <- featureNames(eset)\n'
                f'write.csv(t(exprs_matrix), file="{str(out_h5ad.with_suffix(".csv"))}")\n'
            )
            # Note: This writes CSV first, then we convert. In practice,
            # calling R from here and then converting back is fragile.
            # Best effort: return a plan that says "needs R runtime".

        except Exception as exc:
            logger.warning("[%s] CEL conversion not available (needs R/oligo): %s", ds_id, exc)

        # ── Fallback: record that .CEL needs R environment ──
        return None  # Let the caller know this requires R

    @staticmethod
    def _convert_bgx_illumina(txt_or_bgx: Path, out_h5ad: Path, ds_id: str) -> Optional[Dict[str, Any]]:
        """Convert Illumina BeadChip data (.bgx or non_normalized.txt) → .h5ad.

        Illumina BeadChip data typically comes as:
          - GPLXXXX_bgx.txt  (probe annotation)
          - GSEXXXX_non_normalized.txt  (expression matrix: probes × samples)

        The non_normalized.txt file has:
          - Columns: PROBE_ID, Sample1_AVG_Signal, Sample1_Detection_Pval,
                     Sample2_AVG_Signal, Sample2_Detection_Pval, ...
          - We extract only AVG_Signal columns.
        """
        try:
            import pandas as pd
            import anndata as ad
            import numpy as np

            path_str = str(txt_or_bgx)

            # If it's a .bgx file, try to read and find the expression data
            if path_str.endswith('.bgx') or path_str.endswith('.bgx.gz'):
                # .bgx is XML — not directly convertible without limma
                logger.info("[%s] .bgx is XML format, needs limma::read.ilmn in R", ds_id)
                return None

            # Read as tab-separated (Illumina default)
            df = pd.read_csv(path_str, sep='\t', index_col=0, low_memory=False)

            # ── Illumina-specific: extract AVG_Signal columns ──
            signal_cols = [c for c in df.columns if 'AVG_Signal' in c or 'Signal' in c]
            detection_cols = [c for c in df.columns if 'Detection' in c or 'Pval' in c or 'P_val' in c]

            if signal_cols:
                expr = df[signal_cols].copy()
                # Clean column names: "Sample1_AVG_Signal" → "Sample1"
                expr.columns = [c.replace('_AVG_Signal', '').replace('AVG_Signal', '').strip('_')
                                for c in expr.columns]
            elif len(df.columns) > 2:
                # Not Illumina-format; try generic text matrix
                expr = df
            else:
                return None

            # Convert to numeric
            expr = expr.apply(pd.to_numeric, errors='coerce')
            expr = expr.dropna(axis=0, how='all').dropna(axis=1, how='all')

            if expr.shape[0] == 0 or expr.shape[1] == 0:
                return None

            # Illumina data is typically probes × samples; transpose to samples × probes
            if expr.shape[0] > expr.shape[1] * 2:
                expr = expr.T

            adata = ad.AnnData(X=expr.values.astype(np.float32),
                               obs=pd.DataFrame(index=expr.index.astype(str)),
                               var=pd.DataFrame(index=expr.columns.astype(str)))
            adata.write_h5ad(out_h5ad)
            return {"id": ds_id, "status": "curated", "output_h5ad": str(out_h5ad),
                    "method": "illumina_bgx", "n_cells": adata.n_obs, "n_genes": adata.n_vars}
        except Exception as exc:
            logger.warning("[%s] BGX conversion failed: %s", ds_id, exc)
            return None
