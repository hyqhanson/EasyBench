    @staticmethod
    def _run_python(code: str, ds_dir: Path, out_dir: Path, ds_id: str) -> None:
        """Execute a Python code snippet for custom conversion.

        The code has access to:
            ds_dir (str)     — path to dataset directory
            out_h5ad (str)   — path where curated.h5ad should be written
            available_files  — dict: {filename: full_path} of all files under ds_dir

        Execution happens with cwd=ds_dir so relative paths in the code work.
        """
        out_h5ad = str(out_dir / "curated.h5ad")

        # Build a map of filenames → full paths so LLM code can find files
        file_map = {}
        for f in sorted(ds_dir.rglob("*")):
            if f.is_file():
                rel = str(f.relative_to(ds_dir))
                file_map[rel] = str(f)
                # Also index by basename for convenience
                file_map[f.name] = str(f)

        wrapper = (
            f"import sys, os\n"
            f"os.chdir({str(ds_dir)!r})\n"
            f"ds_dir = {str(ds_dir)!r}\n"
            f"out_h5ad = {out_h5ad!r}\n"
            f"available_files = {file_map!r}\n"
            f"# Helper: find file by partial name match\n"
            f"def find_file(pattern):\n"
            f"    import fnmatch\n"
            f"    for name, path in available_files.items():\n"
            f"        if fnmatch.fnmatch(name, '*' + pattern + '*') or pattern in name:\n"
            f"            return path\n"
            f"    return None\n"
            f"{code}\n"
            f"# Verify output\n"
            f"if not os.path.exists(out_h5ad):\n"
            f"    raise FileNotFoundError(f'curated.h5ad not created at {{out_h5ad}}')\n"
        )
        subprocess.run([sys.executable, "-c", wrapper], check=True, timeout=1800,
                       capture_output=True, text=True, cwd=str(ds_dir))

    @staticmethod
    def _run_r(code: str, ds_dir: Path, out_dir: Path, ds_id: str) -> None:
        """Execute an R code snippet.

        Before running, automatically converts curated.h5ad → Seurat RDS
        so R scripts can load the expression matrix via Seurat.
        The bridge file is written to ds_dir/_bridge/curated_seurat.rds.
        """
        # ── Auto-generate h5ad → RDS bridge for R scripts ──
        bridge_dir = ds_dir / "_bridge"
        bridge_dir.mkdir(parents=True, exist_ok=True)
        rds_bridge = bridge_dir / "curated_seurat.rds"

        # Find curated.h5ad (search paper dir)
        import anndata as ad, pandas as pd, numpy as np
        h5ads = sorted(ds_dir.parent.parent.rglob("curated.h5ad"),
                       key=lambda p: p.stat().st_size, reverse=True)
        if h5ads and not rds_bridge.exists():
            h5ad_path = h5ads[0]
            try:
                a = ad.read_h5ad(h5ad_path)
                X = a.X.toarray() if hasattr(a.X, 'toarray') else a.X
                df = pd.DataFrame(X, index=a.obs_names.astype(str),
                                  columns=a.var_names.astype(str))
                csv_path = bridge_dir / "_counts.csv"
                df.to_csv(csv_path)

                r_code_bridge = (
                    'library(Seurat)\n'
                    'counts <- read.csv("%s", row.names=1, check.names=FALSE)\n'
                    'seurat_obj <- CreateSeuratObject(counts = t(counts))\n'
                    'saveRDS(seurat_obj, "%s")\n'
                ) % (csv_path.as_posix(), rds_bridge.as_posix())
                r_script = bridge_dir / "_bridge.R"
                r_script.write_text(r_code_bridge, encoding="utf-8")
                import subprocess as _sp
                _sp.run(["Rscript", str(r_script)], capture_output=True,
                        text=True, timeout=600, cwd=str(bridge_dir))
                logger.info("[%s] h5ad→RDS bridge created", ds_id[:30])
            except Exception as exc:
                logger.warning("[%s] h5ad→RDS bridge failed: %s", ds_id[:30], exc)

        # ── Execute the R script ──
        out_h5ad = str(out_dir / "curated.h5ad")
        wrapper = (
            f'ds_dir <- "{ds_dir}"\n'
            f'out_h5ad <- "{out_h5ad}"\n'
            f'{code}\n'
            f'if (!file.exists(out_h5ad)) stop("curated.h5ad not created")\n'
        )
        rscript = ds_dir / "_curation_step.R"
        rscript.write_text(wrapper, encoding="utf-8")
        try:
            subprocess.run(["Rscript", str(rscript)], check=True, timeout=1800,
                           capture_output=True, text=True, cwd=str(ds_dir))
        finally:
            if rscript.exists():
                rscript.unlink()

