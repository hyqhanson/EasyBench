    @staticmethod
    def _ensure_h5ad_to_rds_bridge(work_dir: Path, paper_dir: Path) -> Optional[Path]:
        """Convert curated.h5ad → Seurat RDS for R scripts that need Seurat input.

        Scans paper_dir for curated.h5ad files. If found, converts the first
        one to a Seurat R object (.rds) in work_dir.  Returns the rds path or None.
        """
        # Find the curated.h5ad (prefer the largest one)
        h5ads = sorted(paper_dir.rglob("curated.h5ad"),
                       key=lambda p: p.stat().st_size, reverse=True)
        if not h5ads:
            return None

        h5ad_path = h5ads[0]
        out_rds = work_dir / "curated_seurat.rds"

        try:
            import anndata as ad
            import numpy as np

            a = ad.read_h5ad(h5ad_path)

            # ── Create a Python script that converts AnnData → H5AD → SeuratDisk ──
            # Write an intermediate CSV from .X (counts), obs, var
            import scipy.sparse as sp
            import pandas as pd

            # Get expression matrix (dense for small, sparse for large)
            X = a.X
            if sp.issparse(X):
                X = X.toarray()

            # Build a CSV with barcodes as row names and gene symbols as cols
            df = pd.DataFrame(X, index=a.obs_names.astype(str),
                              columns=a.var_names.astype(str))
            csv_path = work_dir / "_bridge_counts.csv"
            df.to_csv(csv_path)

            # Write R script to load CSV and save as Seurat RDS
            r_bridge = (
                'library(Seurat)\n'
                'counts <- read.csv("%s", row.names=1, check.names=FALSE)\n'
                'seurat_obj <- CreateSeuratObject(counts = t(counts))\n'
                # Add metadata if available
                '# Add curated metadata\n'
                'saveRDS(seurat_obj, "%s")\n'
                'cat("Seurat RDS written:", "%s", "\\n")\n'
            ) % (csv_path.as_posix(), out_rds.as_posix(), out_rds.as_posix())

            r_script = work_dir / "_h5ad_to_seurat.R"
            r_script.write_text(r_bridge, encoding="utf-8")

            import subprocess
            r = subprocess.run(["Rscript", str(r_script)],
                               capture_output=True, text=True, timeout=600,
                               cwd=str(work_dir))
            if r.returncode != 0:
                logger.warning("h5ad→RDS bridge failed: %s", r.stderr[:200])
                return None

            if out_rds.exists():
                logger.info("Created Seurat RDS bridge: %s (%.0fKB)",
                            out_rds.name, out_rds.stat().st_size / 1024)
                return out_rds

        except Exception as exc:
            logger.warning("h5ad→RDS bridge error: %s", exc)

        return None

