"""CurationExecutor — executes curation_plan.json steps to produce curated.h5ad.

Reads curation_plan.json (generated by AgentCurator), executes each
dataset's curation_steps, and outputs standard .h5ad AnnData files.

Architecture:
    curation_plan.json  →  CurationExecutor.run()
                              ├── executes curation_steps per dataset
                              ├── handles known formats deterministically
                              └── outputs data/{gse_id}/curated.h5ad
"""

from __future__ import annotations

import json
import logging
import subprocess
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional

from .validator import validate_curated_h5ad, cross_validate_with_protocol

logger = logging.getLogger(__name__)


class CurationExecutor:
    """Deterministic runner that executes curation_plan.json steps."""

    def __init__(self, paper_dir: Path, execution_plan: Optional[Dict[str, Any]] = None) -> None:
        self.paper_dir = paper_dir
        self.slug = paper_dir.name
        self.plan: Dict[str, Any] = {}
        self.execution_plan = execution_plan or {}
        self._load_plan()
        # Load execution_plan if not provided
        if not self.execution_plan:
            ep = paper_dir / "execution_plan.json"
            if ep.exists():
                self.execution_plan = json.loads(ep.read_text(encoding="utf-8"))

    def _load_plan(self) -> None:
        cp = self.paper_dir / "curation_plan.json"
        if cp.exists():
            self.plan = json.loads(cp.read_text(encoding="utf-8"))

    def run(self) -> Dict[str, Any]:
        """Execute all curation steps → produce curated.h5ad per dataset.

        Returns:
            {"datasets_curated": int, "datasets_failed": int, "results": [...]}
        """
        datasets = self.plan.get("datasets", [])
        if not datasets:
            return {"datasets_curated": 0, "datasets_failed": 0, "results": [], "error": "no_datasets_in_plan"}

        results = []
        curated_count = 0
        failed_count = 0

        for ds in datasets:
            ds_id = ds.get("id", "unknown")
            fmt = ds.get("detected_format", "unknown")
            is_expr = ds.get("is_expression_data", True)
            steps = ds.get("curation_steps", [])

            if not is_expr:
                logger.info("[%s] %s: skipping non-expression dataset", self.slug[:30], ds_id)
                results.append({"id": ds_id, "status": "skipped_non_expression"})
                continue

            print(f"  🔧 [{self.slug[:40]}] Curating {ds_id} ({fmt})")
            result = self._execute_dataset(ds_id, steps, fmt)

            # ── Post-execution validation (anti-hallucination) ──
            if result.get("status") == "curated":
                out_path = Path(result.get("output_h5ad", ""))
                if out_path.exists():
                    validation = validate_curated_h5ad(out_path)
                    result["validation"] = validation
                    if validation.get("valid"):
                        # Cross-validate with execution_plan expectations
                        cross = cross_validate_with_protocol(
                            validation, self.execution_plan, ds_id
                        )
                        result["cross_validation"] = cross
                        if not cross.get("matched", True):
                            result["status"] = "curated_but_mismatched"
                            print(f"     ⚠️  Cross-validation mismatch: {cross['mismatches']}")
                    else:
                        result["status"] = "curated_but_invalid"
                        print(f"     ❌ Validation failed: {validation['errors']}")

            results.append(result)

            if result.get("status") == "curated":
                curated_count += 1
            else:
                failed_count += 1

        return {
            "datasets_curated": curated_count,
            "datasets_failed": failed_count,
            "results": results,
        }

    def _execute_dataset(self, ds_id: str, steps: List[Dict[str, str]], fmt: str = "unknown") -> Dict[str, Any]:
        """Execute curation steps for one dataset.

        Returns {"id": ds_id, "status": "curated"|"failed", "output_h5ad": "..."}
        """
        # Determine data source directory
        up = self.paper_dir / "unpacked_data"
        data_root = up if up.exists() else (self.paper_dir / "data")
        ds_dir = data_root / ds_id

        # Output location
        out_dir = data_root / ds_id
        out_h5ad = out_dir / "curated.h5ad"

        # -- Fuzzy-find the actual data directory --
        # LLM may report dataset IDs as filenames (e.g. "GSE255900_raw_count.txt")
        # or as directory names (e.g. "GSE255900").  We try exact match first,
        # then fuzzy match by prefix, then file-name-in-directory match.
        ds_dir = data_root / ds_id
        if not ds_dir.exists():
            # Fuzzy match 1: prefix — e.g. ds_id="GSE255900_raw_count.txt" → dir starts with "GSE255900"
            matched = None
            candidates = sorted(data_root.iterdir())
            # Remove known suffixes from ds_id to find prefix
            for suffix in ('_raw_count.txt', '_miRNA_count.txt', '_mRNA.txt', '_LncRNA.txt',
                           '_standardized.h5ad', '_curated.h5ad', '.txt', '.csv', '.tsv', '.gz'):
                if ds_id.endswith(suffix):
                    prefix_candidate = ds_id[:-len(suffix)]
                    if prefix_candidate:
                        for d in candidates:
                            if d.is_dir() and d.name == prefix_candidate:
                                matched = d
                                break
                        if matched:
                            break
            # Fuzzy match 2: dir starts with the same GSE/GSM prefix
            if not matched:
                gse_match = __import__('re').match(r'(GSE\d+|GSM\d+)', ds_id)
                if gse_match:
                    prefix = gse_match.group(1)
                    for d in candidates:
                        if d.is_dir() and d.name.startswith(prefix):
                            matched = d
                            break
            # Fuzzy match 3: any dir that contains the ds_id as a file
            if not matched:
                for d in candidates:
                    if d.is_dir() and any(f.name == ds_id or ds_id in f.name for f in d.iterdir()):
                        matched = d
                        break
            if matched:
                ds_dir = matched
                # Use a SEPARATE output path to avoid "same file" conflicts
                out_dir = data_root / f"._{ds_id}_tmp"
                out_dir.mkdir(parents=True, exist_ok=True)
                out_h5ad = out_dir / "curated.h5ad"
                logger.info("[%s] Fuzzy-matched '%s' → '%s' (output→%s)", ds_id[:30], ds_id, matched.name, out_dir.name)
            else:
                return {"id": ds_id, "status": "failed", "error": f"dataset dir not found: {ds_dir}"}

        # ── Step 1: Try deterministic fallback FIRST (more reliable than LLM code) ──
        # This handles known formats (10X mtx, h5ad, csv, RDS) using well-tested
        # converters including sc_standardize_input.  Only if this fails do we
        # try the LLM-generated steps.
        logger.info("[%s] Attempting deterministic fallback for '%s'", ds_id[:30], fmt)
        fallback = self._deterministic_fallback(ds_dir, out_h5ad, ds_id)
        if fallback:
            logger.info("[%s] Deterministic fallback succeeded: method=%s", ds_id[:30],
                        fallback.get('method', '?'))
            return fallback

        # ── Step 2: Try LLM-provided steps (if any) ──
        # LLM code may handle edge cases that deterministic fallback misses.
        actual_steps = [s for s in steps if s.get("command", "").strip()]
        for i, step in enumerate(actual_steps):
            tool = step.get("tool", "").strip()
            cmd = step.get("command", "").strip()

            print(f"     Step {i+1}/{len(actual_steps)}: [{tool}] {cmd[:80]}...")

            try:
                if tool == "gunzip":
                    self._run_shell(cmd, cwd=str(ds_dir))
                elif tool == "tar":
                    self._run_shell(cmd, cwd=str(ds_dir))
                elif tool == "python":
                    self._run_python(cmd, ds_dir, out_dir, ds_id)
                elif tool == "R":
                    self._run_r(cmd, ds_dir, out_dir, ds_id)
                elif tool == "manual":
                    print(f"     ⚠️  Manual step: {cmd}")
                else:
                    print(f"     ⚠️  Unknown tool: {tool} — executing as shell")
                    self._run_shell(cmd, cwd=str(ds_dir))
            except Exception as exc:
                return {"id": ds_id, "status": "failed",
                        "error": f"step {i+1} failed: {exc}", "step": step}

        # ── After executing steps, try deterministic fallback ──
        # ALWAYS try fallback — LLM steps may fail or be empty, but we have
        # well-known format converters as a safety net.
        if not out_h5ad.exists():
            # Check if LLM created a differently-named h5ad (e.g. "GSE274171_standardized.h5ad")
            alt_h5ads = list(ds_dir.rglob("*.h5ad"))
            if alt_h5ads:
                import shutil
                # Find the newest .h5ad created during this run
                newest = max(alt_h5ads, key=lambda p: p.stat().st_mtime)
                if newest.name != "curated.h5ad":
                    shutil.move(str(newest), str(out_h5ad))
                    logger.info("[%s] Renamed '%s' → 'curated.h5ad'", ds_id, newest.name)

        if not out_h5ad.exists():
            fallback = self._deterministic_fallback(ds_dir, out_h5ad, ds_id)
            if fallback:
                return fallback

        if out_h5ad.exists():
            return {"id": ds_id, "status": "curated", "output_h5ad": str(out_h5ad)}
        else:
            return {"id": ds_id, "status": "failed",
                    "error": "steps completed but no curated.h5ad produced"}

    # ------------------------------------------------------------------
    # Deterministic fallback — for common formats, bypass LLM steps
    # ------------------------------------------------------------------

    def _deterministic_fallback(self, ds_dir: Path, out_h5ad: Path, ds_id: str) -> Optional[Dict[str, Any]]:
        """Try deterministic conversion for known data layouts.

        This is the safety net — if the LLM-generated steps don't produce
        output, we fall back to well-known patterns.
        """
        try:
            # --- Pattern 1: 10X mtx (matrix.mtx + barcodes + features) ---
            # Search recursively — 10X files are often in RAW/ subdirectories
            # Also match _matrix.mtx patterns (e.g. GSM8492747_CtrlKO_..._matrix.mtx)
            mtx_candidates = list(ds_dir.rglob("matrix.mtx*")) + list(ds_dir.rglob("*_matrix.mtx*"))
            if mtx_candidates:
                for mtx_file in mtx_candidates:
                    parent = mtx_file.parent
                    # Try standard barcodes.tsv / features.tsv first
                    has_barcodes = any(parent.glob("barcodes.tsv*"))
                    has_features = any(parent.glob("features.tsv*")) or any(parent.glob("genes.tsv*"))
                    if has_barcodes and has_features:
                        logger.info("[%s] Detected standard 10X mtx in %s", ds_id, parent)
                        return self._convert_10x_mtx(parent, out_h5ad, ds_id)
                # Fallback: try GSM-prefixed files (*barcode* and *feature*)
                for mtx_file in mtx_candidates:
                    parent = mtx_file.parent
                    has_barcodes = any(parent.glob("*barcode*"))
                    has_features = any(parent.glob("*feature*"))
                    if has_barcodes and has_features:
                        logger.info("[%s] Detected GSM-prefixed 10X mtx in %s", ds_id, parent)
                        return self._convert_10x_mtx(parent, out_h5ad, ds_id)
                # If mtx found but no barcodes/features, try the first one anyway
                logger.info("[%s] Detected loose .mtx in %s (no barcodes/features)", ds_id, mtx_candidates[0].parent)

            # --- Pattern 2: .h5ad directly (skip curated.h5ad — we're creating it) ---
            h5ad_files = [f for f in ds_dir.rglob("*.h5ad") if f.name != "curated.h5ad"]
            if h5ad_files:
                import shutil
                shutil.copy2(h5ad_files[0], out_h5ad)
                logger.info("[%s] Copied existing .h5ad", ds_id)
                return {"id": ds_id, "status": "curated", "output_h5ad": str(out_h5ad),
                        "method": "copy_existing_h5ad"}

            # --- Pattern 3: .h5 (10X HDF5) ---
            h5_files = list(ds_dir.rglob("*.h5"))
            if h5_files:
                return self._convert_10x_h5(h5_files[0], out_h5ad, ds_id)

            # --- Pattern 4: .CEL (Affymetrix microarray) ---
            cel_files = list(ds_dir.rglob("*.CEL")) + list(ds_dir.rglob("*.CEL.gz"))
            if cel_files and not mtx_candidates:
                logger.info("[%s] Detected Affymetrix .CEL files (%d files)", ds_id, len(cel_files))
                return self._convert_cel_affymetrix(cel_files, out_h5ad, ds_id)

            # --- Pattern 5: .bgx (Illumina BeadChip) ---
            bgx_files = list(ds_dir.rglob("*.bgx")) + list(ds_dir.rglob("*.bgx.gz"))
            if bgx_files:
                logger.info("[%s] Detected Illumina .bgx files", ds_id)
                # bgx is an annotation/control file; look for accompanying non-normalized txt
                txt_files = list(ds_dir.rglob("*non_normalized*.txt*"))
                if txt_files:
                    return self._convert_bgx_illumina(txt_files[0], out_h5ad, ds_id)
                # Fallback: try bgx itself
                return self._convert_bgx_illumina(bgx_files[0], out_h5ad, ds_id)

            # --- Pattern 6: .csv / .tsv count matrix ---
            csv_files = list(ds_dir.rglob("*.csv")) + list(ds_dir.rglob("*.csv.gz"))
            txt_files = list(ds_dir.rglob("*.txt")) + list(ds_dir.rglob("*.txt.gz"))
            tsv_files = list(ds_dir.rglob("*.tsv")) + list(ds_dir.rglob("*.tsv.gz"))
            all_text = csv_files + txt_files + tsv_files
            # Filter out small metadata files (< 100KB)
            all_text = [f for f in all_text if f.stat().st_size > 100 * 1024]
            if all_text:
                return self._convert_text_matrix(all_text[0], out_h5ad, ds_id)

            # --- Pattern 7: .rds (Seurat R object) ---
            rds_files = list(ds_dir.rglob("*.rds"))
            if rds_files:
                return self._convert_rds(rds_files[0], out_h5ad, ds_id)

        except Exception as exc:
            logger.warning("[%s] Deterministic fallback failed: %s", ds_id, exc)

        return None

    # ------------------------------------------------------------------
    # Format-specific converters
    # ------------------------------------------------------------------

    @staticmethod
    def _convert_10x_mtx(mtx_dir: Path, out_h5ad: Path, ds_id: str) -> Optional[Dict[str, Any]]:
        """Convert 10X mtx directory → .h5ad using scanpy or scipy.

        Handles both standard naming (matrix.mtx, barcodes.tsv, features.tsv)
        and GSM-prefixed naming (GSMxxxx_*_matrix.mtx, etc.).
        """
        try:
            import scanpy as sc
            import pandas as pd
            import anndata as ad
            import scipy.io
            import numpy as np

            # Check for standard 10X filenames
            has_standard_mtx = any((mtx_dir / f).exists() for f in ['matrix.mtx', 'matrix.mtx.gz'])
            has_barcodes = any(mtx_dir.glob('*barcode*')) or any(mtx_dir.glob('*barcodes*'))
            has_features = any(mtx_dir.glob('*feature*')) or any(mtx_dir.glob('*features*'))

            if has_standard_mtx and has_barcodes and has_features:
                # Standard 10X layout
                adata = sc.read_10x_mtx(str(mtx_dir), var_names="gene_symbols", cache=False)
                adata.write_h5ad(out_h5ad)
                return {"id": ds_id, "status": "curated", "output_h5ad": str(out_h5ad),
                        "method": "scanpy.read_10x_mtx", "n_cells": adata.n_obs, "n_genes": adata.n_vars}

            # Non-standard naming: find all _matrix.mtx files
            mtx_files = sorted(mtx_dir.rglob('*_matrix.mtx*')) or sorted(mtx_dir.rglob('matrix.mtx*'))
            if not mtx_files:
                return None

            # Process each GSM sample independently and merge at the end
            # This avoids OOM from trying to load all GSMs at once
            adatas = []
            for mtx_f in mtx_files:
                # Extract GSM prefix: everything before _matrix.mtx
                stem = mtx_f.name.replace('_matrix.mtx', '').replace('_matrix.mtx.gz', '')
                bc_pattern = stem + '*barcode*'
                ft_pattern = stem + '*feature*'
                bcs = list(mtx_f.parent.glob(bc_pattern)) or list(mtx_f.parent.glob(stem + '*barcodes*'))
                fts = list(mtx_f.parent.glob(ft_pattern)) or list(mtx_f.parent.glob(stem + '*features*'))
                if not bcs or not fts:
                    continue

                # --- Read independently per GSM to limit memory ---
                mtx = scipy.io.mmread(str(mtx_f))
                # Convert to CSR (AnnData requires CSR/CSC, COO not supported)
                if hasattr(mtx, 'tocsr'):
                    mtx = mtx.tocsr()
                else:
                    mtx = np.array(mtx).astype(np.float32)

                bc = pd.read_csv(bcs[0], header=None, sep='\t')[0].astype(str).tolist()
                ft = pd.read_csv(fts[0], header=None, sep='\t')

                # Determine orientation: scipy mmread returns genes x cells.
                # barcodes = cells, features = genes.
                n_bc = len(bc)
                n_ft = len(ft)
                if mtx.shape[0] == n_bc and mtx.shape[1] == n_ft:
                    # Already cells x genes — convert to float32
                    mtx = mtx.astype(np.float32)
                elif mtx.shape[1] == n_bc and mtx.shape[0] == n_ft:
                    # genes x cells → transpose
                    mtx = mtx.T.tocsr().astype(np.float32)
                else:
                    continue

                a = ad.AnnData(X=mtx,
                               obs=pd.DataFrame(index=bc).rename_axis(index=None),
                               var=pd.DataFrame(index=ft.iloc[:,0].astype(str)).rename_axis(index=None))
                a.obs['sample'] = stem[:20]
                a.var_names_make_unique()
                adatas.append(a)

                # Free memory
                del mtx

            if adatas:
                import warnings
                with warnings.catch_warnings():
                    warnings.simplefilter("ignore")
                    combined = ad.concat(adatas, axis=0, join='outer', index_unique='-')
                combined.write_h5ad(out_h5ad)
                return {"id": ds_id, "status": "curated", "output_h5ad": str(out_h5ad),
                        "method": "scanpy_gsm_mtx", "n_cells": combined.n_obs, "n_genes": combined.n_vars}

        except Exception as exc:
            logger.warning("[%s] 10X mtx conversion failed: %s", ds_id, exc)
            return None

    @staticmethod
    def _convert_10x_h5(h5_path: Path, out_h5ad: Path, ds_id: str) -> Optional[Dict[str, Any]]:
        """Convert 10X HDF5 → .h5ad using scanpy."""
        try:
            import scanpy as sc
            adata = sc.read_10x_h5(str(h5_path))
            adata.write_h5ad(out_h5ad)
            return {"id": ds_id, "status": "curated", "output_h5ad": str(out_h5ad),
                    "method": "scanpy.read_10x_h5", "n_cells": adata.n_obs, "n_genes": adata.n_vars}
        except Exception as exc:
            logger.warning("[%s] 10X h5 conversion failed: %s", ds_id, exc)
            return None

    @staticmethod
    def _convert_text_matrix(txt_path: Path, out_h5ad: Path, ds_id: str) -> Optional[Dict[str, Any]]:
        """Convert .csv/.tsv/.txt matrix → .h5ad using pandas.

        Handles:
          - Standard tab/comma-separated matrices
          - Gzipped matrices (.gz)
          - Gene names in first column (non-numeric → treated as index)
          - Auto-transpose detection (samples × genes → genes × samples)
        """
        try:
            import pandas as pd
            import anndata as ad
            import numpy as np
            import gzip

            # Determine separator
            ext = txt_path.suffix.lower()
            path_str = str(txt_path)
            is_gz = path_str.endswith('.gz')

            # Peek at first line to detect separator
            open_func = gzip.open if is_gz else open
            with open_func(path_str, 'rt', encoding='utf-8', errors='replace') as fh:
                first_line = fh.readline()
                second_line = fh.readline() if not is_gz else fh.readline()

            # Detect separator: count tabs vs commas
            n_tabs = first_line.count('\t')
            n_commas = first_line.count(',')
            sep = '\t' if n_tabs >= n_commas else ','

            # Check if first column is gene names (non-numeric first cell of data)
            # Read with first column as index, then check if index looks like gene names
            if is_gz:
                df = pd.read_csv(path_str, sep=sep, index_col=0,
                                 compression='gzip', low_memory=False)
            else:
                df = pd.read_csv(path_str, sep=sep, index_col=0, low_memory=False)

            # ── Handle non-numeric data (gene names / metadata rows) ──
            # Try to convert all columns to numeric; track which failed
            numeric_df = df.apply(pd.to_numeric, errors='coerce')
            # If all values became NaN → likely gene names as column headers
            if numeric_df.isna().all().all():
                # Transpose and try again: maybe samples are rows and genes are columns
                df_t = df.T
                numeric_df_t = df_t.apply(pd.to_numeric, errors='coerce')
                if not numeric_df_t.isna().all().all():
                    df = df_t
                    numeric_df = numeric_df_t

            # Drop rows/columns that are all NaN
            numeric_df = numeric_df.dropna(axis=0, how='all').dropna(axis=1, how='all')

            if numeric_df.shape[0] == 0 or numeric_df.shape[1] == 0:
                return None

            # Auto-transpose: if rows look like samples (fewer rows than columns,
            # and rows have short names), transpose to genes × samples
            if numeric_df.shape[0] < numeric_df.shape[1] and numeric_df.shape[0] < 5000:
                numeric_df = numeric_df.T

            adata = ad.AnnData(X=numeric_df.values.astype(np.float32),
                               obs=pd.DataFrame(index=numeric_df.index.astype(str)),
                               var=pd.DataFrame(index=numeric_df.columns.astype(str)))
            adata.write_h5ad(out_h5ad)
            return {"id": ds_id, "status": "curated", "output_h5ad": str(out_h5ad),
                    "method": "pandas_text_matrix_v2",
                    "n_cells": adata.n_obs, "n_genes": adata.n_vars}
        except Exception as exc:
            logger.warning("[%s] Text matrix conversion failed: %s", ds_id, exc)
            return None

    @staticmethod
    def _convert_rds(rds_path: Path, out_h5ad: Path, ds_id: str) -> Optional[Dict[str, Any]]:
        """Convert .rds Seurat object → .h5ad via pyreadr."""
        try:
            import pyreadr
            result = pyreadr.read_r(str(rds_path))
            if result:
                # pyreadr returns a dict: {name: DataFrame}
                key = list(result.keys())[0]
                df = result[key]
                import anndata as ad
                import numpy as np
                import pandas as pd
                adata = ad.AnnData(X=df.values.astype(np.float32),
                                   obs=pd.DataFrame(index=df.index),
                                   var=pd.DataFrame(index=df.columns))
                adata.write_h5ad(out_h5ad)
                return {"id": ds_id, "status": "curated", "output_h5ad": str(out_h5ad),
                        "method": "pyreadr", "n_cells": adata.n_obs, "n_genes": adata.n_vars}
        except Exception as exc:
            logger.warning("[%s] RDS conversion failed: %s", ds_id, exc)
        return None

